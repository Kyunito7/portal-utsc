-- ---- 8.10 Préstamos de biblioteca ---------------------------------------
CREATE FUNCTION fn_prestamos_bi() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  IF NEW.fecha_limite IS NULL THEN
    NEW.fecha_limite := NEW.fecha_inicio + CASE WHEN NEW.tipo = 'prestamo' THEN 15 ELSE 2 END;
  END IF;
  IF NEW.estado = 'activo' THEN
    IF (SELECT COUNT(*) FROM prestamos WHERE alumno_id = NEW.alumno_id AND estado = 'activo') >= 3 THEN
      RAISE EXCEPTION 'Máximo 3 préstamos/reservas activos por alumno';
    END IF;
    IF (SELECT ejemplares_disponibles FROM libros WHERE id = NEW.libro_id) < 1 THEN
      RAISE EXCEPTION 'No hay ejemplares disponibles de este libro';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_prestamos_bi BEFORE INSERT ON prestamos FOR EACH ROW EXECUTE FUNCTION fn_prestamos_bi();

CREATE FUNCTION fn_prestamos_ai() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  IF NEW.estado = 'activo' THEN
    UPDATE libros SET ejemplares_disponibles = ejemplares_disponibles - 1 WHERE id = NEW.libro_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_prestamos_ai AFTER INSERT ON prestamos FOR EACH ROW EXECUTE FUNCTION fn_prestamos_ai();

CREATE FUNCTION fn_prestamos_bu() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  -- No se puede reactivar algo ya cerrado
  IF OLD.estado <> 'activo' AND NEW.estado = 'activo' THEN
    RAISE EXCEPTION 'Un préstamo cerrado no se puede reactivar';
  END IF;
  -- Renovación: solo préstamos activos, máximo 1 vez, +15 días
  IF NEW.renovaciones > OLD.renovaciones THEN
    IF OLD.tipo <> 'prestamo' OR OLD.estado <> 'activo' THEN
      RAISE EXCEPTION 'Solo se pueden renovar préstamos activos (no reservas)';
    END IF;
    IF OLD.renovaciones >= 1 THEN
      RAISE EXCEPTION 'Este préstamo ya se renovó una vez';
    END IF;
    NEW.fecha_limite := OLD.fecha_limite + 15;
  END IF;
  -- Reserva que se convierte en préstamo
  IF OLD.tipo = 'reserva' AND NEW.tipo = 'prestamo' AND OLD.estado = 'activo' THEN
    NEW.fecha_inicio := CURRENT_DATE;
    NEW.fecha_limite := CURRENT_DATE + 15;
  END IF;
  -- Al cerrar, se registra la fecha de devolución
  IF OLD.estado = 'activo' AND NEW.estado = 'devuelto' AND NEW.fecha_devolucion IS NULL THEN
    NEW.fecha_devolucion := CURRENT_DATE;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_prestamos_bu BEFORE UPDATE ON prestamos FOR EACH ROW EXECUTE FUNCTION fn_prestamos_bu();

CREATE FUNCTION fn_prestamos_au() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  IF OLD.estado = 'activo' AND NEW.estado IN ('devuelto','cancelado') THEN
    UPDATE libros SET ejemplares_disponibles = ejemplares_disponibles + 1 WHERE id = NEW.libro_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_prestamos_au AFTER UPDATE ON prestamos FOR EACH ROW EXECUTE FUNCTION fn_prestamos_au();

-- ---- 8.11 DriverUTSC --------------------------------------------------------
CREATE FUNCTION fn_reservas_valida() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
DECLARE v_conductor INT; v_borrada TIMESTAMPTZ; v_asientos INT; v_ocupados INT;
BEGIN
  IF NEW.estado = 'cancelada' THEN
    NEW.cancelada_en := COALESCE(NEW.cancelada_en, now());
    RETURN NEW;
  END IF;
  -- Solo se valida cuando la reserva queda activa
  SELECT conductor_id, deleted_at, asientos INTO v_conductor, v_borrada, v_asientos
    FROM rutas_driver WHERE id = NEW.ruta_id;
  IF v_borrada IS NOT NULL THEN
    RAISE EXCEPTION 'La ruta ya no está disponible';
  END IF;
  IF v_conductor = NEW.pasajero_id THEN
    RAISE EXCEPTION 'El conductor no puede reservar un lugar en su propia ruta';
  END IF;
  IF EXISTS (SELECT 1 FROM reservas_viaje
             WHERE ruta_id = NEW.ruta_id AND pasajero_id = NEW.pasajero_id
               AND estado = 'activa' AND (TG_OP = 'INSERT' OR id <> NEW.id)) THEN
    RAISE EXCEPTION 'Ya tienes una reserva activa en esta ruta';
  END IF;
  SELECT COUNT(*) INTO v_ocupados FROM reservas_viaje
   WHERE ruta_id = NEW.ruta_id AND estado = 'activa' AND (TG_OP = 'INSERT' OR id <> NEW.id);
  IF v_ocupados >= v_asientos THEN
    RAISE EXCEPTION 'No hay asientos disponibles en esa ruta';
  END IF;
  NEW.cancelada_en := NULL;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_reservas_bi BEFORE INSERT ON reservas_viaje FOR EACH ROW EXECUTE FUNCTION fn_reservas_valida();
CREATE TRIGGER trg_reservas_bu BEFORE UPDATE ON reservas_viaje FOR EACH ROW EXECUTE FUNCTION fn_reservas_valida();

CREATE FUNCTION fn_rutas_bu() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  IF NEW.asientos < (SELECT COUNT(*) FROM reservas_viaje WHERE ruta_id = NEW.id AND estado = 'activa') THEN
    RAISE EXCEPTION 'No puedes bajar los asientos por debajo de las reservas activas';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_rutas_bu BEFORE UPDATE ON rutas_driver FOR EACH ROW EXECUTE FUNCTION fn_rutas_bu();

CREATE FUNCTION fn_rutas_au() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  IF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
    UPDATE reservas_viaje SET estado = 'cancelada', cancelada_en = now()
     WHERE ruta_id = NEW.id AND estado = 'activa';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_rutas_au AFTER UPDATE ON rutas_driver FOR EACH ROW EXECUTE FUNCTION fn_rutas_au();

