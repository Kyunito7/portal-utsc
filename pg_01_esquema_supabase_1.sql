      INSERT INTO notificaciones (usuario_id, modulo, titulo, mensaje)
      VALUES (v_alumno, 'pagos', 'Pago registrado', 'Referencia ' || NEW.referencia);
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_pagos_ai AFTER INSERT ON pagos FOR EACH ROW EXECUTE FUNCTION fn_pagos_ai();

