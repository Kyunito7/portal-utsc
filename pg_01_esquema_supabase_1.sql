CREATE TABLE inscripciones (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alumno_id    INTEGER NOT NULL REFERENCES alumnos(usuario_id) ON DELETE CASCADE,
  materia_id   INTEGER NOT NULL REFERENCES materias(id),
  periodo_id   INTEGER NOT NULL REFERENCES periodos(id),
  calificacion NUMERIC(4,2),
  -- columna calculada: NULL = en curso, >= 8 aprobada, si no reprobada
  estado       TEXT GENERATED ALWAYS AS (
                 CASE WHEN calificacion IS NULL THEN 'en_curso'
                      WHEN calificacion >= 8    THEN 'aprobada'
                      ELSE 'reprobada' END) STORED,
  CONSTRAINT chk_calificacion CHECK (calificacion IS NULL OR calificacion BETWEEN 0 AND 10),
  CONSTRAINT uq_inscripcion UNIQUE (alumno_id, materia_id, periodo_id)
);

