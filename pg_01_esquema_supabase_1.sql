-- =====================================================================
-- BLOQUE 0 · Función genérica para updated_at
-- (reemplaza el "ON UPDATE CURRENT_TIMESTAMP" de MySQL)
-- =====================================================================
CREATE FUNCTION fn_set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

