-- ---- 8.1 Validar alumno (antes sp_validar_alumno) -------------------
CREATE FUNCTION fn_validar_alumno(p_usuario INT, p_matricula TEXT, p_carrera INT, p_grupo INT)
RETURNS void LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
DECLARE v_rol TEXT; v_correo TEXT; v_carrera_grupo INT;
BEGIN
  SELECT rol, correo INTO v_rol, v_correo FROM usuarios WHERE id = p_usuario;
  IF v_rol IS DISTINCT FROM 'alumno' THEN
    RAISE EXCEPTION 'El usuario % no tiene rol alumno', p_usuario;
  END IF;
  IF v_correo <> p_matricula || '@utsc.edu.mx' THEN
    RAISE EXCEPTION 'El correo del alumno debe ser matricula@utsc.edu.mx (esperado %@utsc.edu.mx)', p_matricula;
  END IF;
  IF p_grupo IS NOT NULL THEN
    SELECT carrera_id INTO v_carrera_grupo FROM grupos WHERE id = p_grupo;
    IF v_carrera_grupo IS DISTINCT FROM p_carrera THEN
      RAISE EXCEPTION 'El grupo no pertenece a la carrera del alumno';
    END IF;
  END IF;
END $$;

-- ---- 8.2 Validar horario (antes sp_validar_horario) -----------------
CREATE FUNCTION fn_validar_horario(p_id INT, p_grupo INT, p_docente INT, p_dia TEXT, p_inicio TIME, p_fin TIME)
RETURNS void LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM horario_clases
             WHERE grupo_id = p_grupo AND dia = p_dia
               AND (p_id IS NULL OR id <> p_id)
               AND hora_inicio < p_fin AND hora_fin > p_inicio) THEN
    RAISE EXCEPTION 'El grupo ya tiene una clase que se empalma en ese horario';
  END IF;
  IF EXISTS (SELECT 1 FROM horario_clases
             WHERE docente_id = p_docente AND dia = p_dia
               AND (p_id IS NULL OR id <> p_id)
               AND hora_inicio < p_fin AND hora_fin > p_inicio) THEN
    RAISE EXCEPTION 'El docente ya tiene una clase que se empalma en ese horario';
  END IF;
END $$;

-- ---- 8.3 Usuarios: crear ajustes por defecto ------------------------
CREATE FUNCTION fn_usuarios_ai() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
BEGIN
  INSERT INTO ajustes_usuario (usuario_id) VALUES (NEW.id) ON CONFLICT DO NOTHING;
  RETURN NEW;
END $$;
