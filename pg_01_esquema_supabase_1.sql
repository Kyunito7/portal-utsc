-- ---- 8.9 Pagos ---------------------------------------------------------
CREATE FUNCTION fn_pagos_bi() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
DECLARE v_estado TEXT; v_monto NUMERIC; v_pref TEXT; v_sig INT;
BEGIN
  SELECT estado, monto INTO v_estado, v_monto FROM cargos WHERE id = NEW.cargo_id;
  IF v_estado IS DISTINCT FROM 'pendiente' THEN
    RAISE EXCEPTION 'Solo se pueden pagar cargos pendientes';
  END IF;
  IF NEW.monto <> v_monto THEN
    RAISE EXCEPTION 'El monto del pago (%) no coincide con el del cargo (%)', NEW.monto, v_monto;
  END IF;
  IF NEW.referencia IS NULL OR NEW.referencia = '' THEN
    v_pref := upper(NEW.metodo) || '-' || to_char(CURRENT_DATE, 'YYYYMMDD') || '-';
    PERFORM pg_advisory_xact_lock(hashtext('ref_pago'));
    SELECT COALESCE(MAX(right(referencia, 4)::int), 0) + 1 INTO v_sig
      FROM pagos WHERE referencia LIKE v_pref || '%';
    NEW.referencia := v_pref || lpad(v_sig::text, 4, '0');
  END IF;
  IF NEW.estado = 'completado' AND NEW.pagado_en IS NULL THEN
    NEW.pagado_en := now();
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_pagos_bi BEFORE INSERT ON pagos FOR EACH ROW EXECUTE FUNCTION fn_pagos_bi();

CREATE FUNCTION fn_pagos_ai() RETURNS trigger
LANGUAGE plpgsql SET search_path = utsc_portal, public AS $$
