  IF NEW.estado IN ('pendiente','en_proceso') AND EXISTS (
       SELECT 1 FROM solicitudes_tramite
       WHERE alumno_id = NEW.alumno_id AND tramite_id = NEW.tramite_id
         AND estado IN ('pendiente','en_proceso')) THEN
    RAISE EXCEPTION 'Ya tienes una solicitud activa de este trámite';
  END IF;
  IF NEW.folio IS NULL OR NEW.folio = '' THEN
    PERFORM pg_advisory_xact_lock(hashtext('folio_tramite'));
    SELECT COALESCE(MAX(split_part(folio, '-', 3)::int), 0) + 1 INTO v_sig
      FROM solicitudes_tramite WHERE folio LIKE 'TRM-' || v_anio || '-%';
    NEW.folio := 'TRM-' || v_anio || '-' || lpad(v_sig::text, 4, '0');
  END IF;
